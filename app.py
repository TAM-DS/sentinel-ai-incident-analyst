"""SENTINEL — read-only Linux incident operations console."""

import os
import shutil
import socket
from datetime import datetime, timezone

import streamlit as st

from src.analysis import offline_example, ALLOWED_RUNBOOKS
from src.collector import collect_events
from src.detector import cluster_findings, detect_events, summarize_findings
from src.privacy import prepare_evidence

st.set_page_config(
    page_title="SENTINEL | Infrastructure Incident Analyst",
    page_icon="🛡️",
    layout="wide",
)

st.markdown("""
<style>
.stApp {background: #0d1420; color: #edf3fa;}
.block-container {padding-top: 2rem; max-width: 1450px;}
h1, h2, h3 {letter-spacing: -0.03em;}
[data-testid="stMetric"] {
    background: #172336;
    border: 1px solid #30435b;
    border-radius: 12px;
    padding: 18px;
}
</style>
""", unsafe_allow_html=True)

st.title("🛡️ SENTINEL")
st.caption("AI INFRASTRUCTURE INCIDENT ANALYST  /  UBUNTU OPERATIONS CONSOLE")
st.info(
    "READ-ONLY MONITORING · Local Linux telemetry · "
    "Human-controlled remediation · No automatic API requests"
)

with st.sidebar:
    st.header("Operations")
    st.write("**Host:**", socket.gethostname())
    st.write("**Mode:** Local observation")
    st.write("**AI execution:** Disabled")
    limit = st.slider("Journal records to examine", 20, 500, 100, 20)
    if st.button("Refresh observations", width="stretch"):
        st.rerun()
    st.divider()
    st.caption("Synthetic demonstration data is explicitly labeled.")

# Local system metrics.
disk = shutil.disk_usage("/")
try:
    load_1m = os.getloadavg()[0]
except OSError:
    load_1m = None

memory = {}
with open("/proc/meminfo", encoding="utf-8") as handle:
    for line in handle:
        if ":" in line:
            name, value = line.split(":", 1)
            memory[name] = int(value.strip().split()[0])

memory_total = memory.get("MemTotal", 0)
memory_available = memory.get("MemAvailable", 0)
memory_used_pct = (
    100 * (memory_total - memory_available) / memory_total
    if memory_total else 0
)
disk_used_pct = 100 * disk.used / disk.total if disk.total else 0

st.subheader("Infrastructure health")
c1, c2, c3, c4 = st.columns(4)
c1.metric("CPU load · 1 min", f"{load_1m:.2f}" if load_1m is not None else "N/A")
c2.metric("Memory utilized", f"{memory_used_pct:.1f}%")
c3.metric("Root disk utilized", f"{disk_used_pct:.1f}%")
c4.metric("CPU cores", str(os.cpu_count() or "N/A"))

st.caption(
    "CPU load is the Linux 1-minute load average, not CPU utilization. "
    "Metrics reflect the local Ubuntu host at refresh time."
)

st.divider()
st.subheader("Linux incident intelligence")

try:
    events = collect_events(limit)
    findings = detect_events(events)
    clusters = cluster_findings(findings)
except Exception as exc:
    st.error(f"Journal collection unavailable: {type(exc).__name__}")
    events, findings, clusters = [], [], []

a, b, c = st.columns(3)
a.metric("Journal events examined", len(events))
b.metric("Deterministic rule matches", len(findings))
c.metric("Grouped conditions", len(clusters))

left, right = st.columns([1, 2])

with left:
    st.markdown("#### Findings by category")
    counts = summarize_findings(findings)
    if counts:
        st.bar_chart(counts)
    else:
        st.success("No configured detection rules matched this sample.")

with right:
    st.markdown("#### Candidate conditions")
    if clusters:
        st.dataframe(
            [{
                "Rule": x["rule_id"],
                "Source": x["source"],
                "Observations": x["event_count"],
                "First seen": x["first_seen"],
                "Last seen": x["last_seen"],
            } for x in clusters],
            width="stretch",
            hide_index=True,
        )
    else:
        st.write("No candidate conditions in the selected journal sample.")

st.caption(
    "A rule match is not a confirmed incident. Grouping by rule and source "
    "does not independently prove the root cause."
)

st.divider()
st.subheader("AI incident assessment")
st.warning(
    "SYNTHETIC DEMONSTRATION — This example is generated by a local fixture. "
    "It is not a live AI response or a diagnosis of this server."
)

demo = [{
    "timestamp": "2026-10-28T12:00:00Z",
    "source": "systemd",
    "priority": "3",
    "message": "synthetic-demo.service: Failed to start",
}]

evidence = prepare_evidence(demo)
report = offline_example(evidence)

st.markdown(f"### {report.title}")
st.write(report.summary)

d1, d2, d3 = st.columns(3)
d1.metric("Classification", report.severity.title())
d2.metric("Evidence reference", ", ".join(report.evidence_ids))
d3.metric("Runbook ID", report.runbook_id)

st.markdown("**Uncertainty:** " + report.uncertainty)
st.markdown("**Approved operator guidance:** " + ALLOWED_RUNBOOKS[report.runbook_id])
st.caption(
    "Recommendations require human review. No automatic remediation "
    "or shell execution is implemented."
)

with st.expander("Inspect synthetic evidence"):
    st.json(evidence)

st.divider()
st.caption(
    "SENTINEL · Python · Linux journald · SQLite evidence pipeline · "
    "Deterministic detection · OpenAI integration tested separately · "
    "Human authority retained"
)
